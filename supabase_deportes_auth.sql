-- Crear tabla de PINs y Google Sheets exclusiva para Colonia y COYFD (Profe y Coordinación)
CREATE TABLE IF NOT EXISTS public.deportes_auth (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deporte TEXT NOT NULL UNIQUE,
  pin TEXT NOT NULL,
  pin_coord TEXT,
  email_sheet TEXT,
  sheet_url TEXT,
  script_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Si la tabla ya existía, aseguramos que tenga las columnas necesarias:
ALTER TABLE public.deportes_auth ADD COLUMN IF NOT EXISTS pin_coord TEXT;
ALTER TABLE public.deportes_auth ADD COLUMN IF NOT EXISTS email_sheet TEXT;
ALTER TABLE public.deportes_auth ADD COLUMN IF NOT EXISTS sheet_url TEXT;
ALTER TABLE public.deportes_auth ADD COLUMN IF NOT EXISTS script_url TEXT;

-- Habilitar RLS
ALTER TABLE public.deportes_auth ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lectura publica de deportes_auth" ON public.deportes_auth;
CREATE POLICY "Lectura publica de deportes_auth"
  ON public.deportes_auth
  FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Actualizacion de sheet_url en deportes_auth" ON public.deportes_auth;
CREATE POLICY "Actualizacion de sheet_url en deportes_auth"
  ON public.deportes_auth
  FOR UPDATE
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Insercion en deportes_auth" ON public.deportes_auth;
CREATE POLICY "Insercion en deportes_auth"
  ON public.deportes_auth
  FOR INSERT
  WITH CHECK (true);

